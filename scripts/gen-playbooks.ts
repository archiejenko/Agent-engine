import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT } from "./lib.ts";

// Bundles playbooks/*/SKILL.md into TypeScript so the Cloudflare Worker (no filesystem) can create
// tasks. A test fails if this file is out of date: run `pnpm gen:playbooks` after editing a SKILL.md.
export function bundle(): string {
  const dir = resolve(ROOT, "playbooks");
  const entries = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort()
    .map(
      (name) =>
        `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(resolve(dir, name, "SKILL.md"), "utf8"))},`,
    );
  return `// GENERATED by scripts/gen-playbooks.ts from playbooks/*/SKILL.md — do not edit by hand.\nexport const BUNDLED_PLAYBOOKS: Record<string, string> = {\n${entries.join("\n")}\n};\n`;
}

if (process.argv[1]?.endsWith("gen-playbooks.ts")) {
  writeFileSync(resolve(ROOT, "packages/infra/src/playbooks.generated.ts"), bundle());
  console.log("wrote packages/infra/src/playbooks.generated.ts");
}
