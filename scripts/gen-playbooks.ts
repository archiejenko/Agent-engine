import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT } from "./lib.ts";

// Bundles playbooks/*/SKILL.md (and each playbook's graph.json, graph plan G2) into TypeScript so the
// Cloudflare Worker (no filesystem) can create tasks and run them as graphs. A test fails if this file is
// out of date: run `pnpm gen:playbooks` after editing a SKILL.md or a graph.json. Folders starting with
// "_" hold prompts that aren't playbooks.
export function bundle(): string {
  const dir = resolve(ROOT, "playbooks");
  const names = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("_"))
    .map((d) => d.name)
    .sort();
  const skills = names.map(
    (name) =>
      `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(resolve(dir, name, "SKILL.md"), "utf8"))},`,
  );
  const graphs = names
    .filter((name) => existsSync(resolve(dir, name, "graph.json")))
    .map(
      (name) =>
        `  ${JSON.stringify(name)}: ${JSON.stringify(JSON.parse(readFileSync(resolve(dir, name, "graph.json"), "utf8")))},`,
    );
  return `// GENERATED by scripts/gen-playbooks.ts from playbooks/*/SKILL.md and graph.json — do not edit by hand.\nexport const BUNDLED_PLAYBOOKS: Record<string, string> = {\n${skills.join("\n")}\n};\n\nexport const BUNDLED_GRAPHS: Record<string, unknown> = {\n${graphs.join("\n")}\n};\n`;
}

if (process.argv[1]?.endsWith("gen-playbooks.ts")) {
  writeFileSync(resolve(ROOT, "packages/infra/src/playbooks.generated.ts"), bundle());
  console.log("wrote packages/infra/src/playbooks.generated.ts");
}
