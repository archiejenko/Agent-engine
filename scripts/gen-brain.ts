import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { ROOT } from "./lib.ts";

// Bundles brain/**/*.md and brain/**/*.csv into the Worker (no filesystem on Cloudflare) for the Vault.
// `pnpm cf:deploy` runs this first, so a deploy always carries the current notes. Locally the API reads
// brain/ from disk instead.
export function collect(dir = resolve(ROOT, "brain")): { path: string; body: string }[] {
  const out: { path: string; body: string }[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(md|csv)$/i.test(name))
        out.push({ path: relative(ROOT, p).split("\\").join("/"), body: readFileSync(p, "utf8") });
    }
  };
  walk(dir);
  return out;
}

if (process.argv[1]?.endsWith("gen-brain.ts")) {
  const notes = collect();
  writeFileSync(
    resolve(ROOT, "apps/api/src/brain.generated.ts"),
    `// GENERATED by scripts/gen-brain.ts from brain/ — regenerated on every deploy; do not edit by hand.\nexport const BRAIN_NOTES: { path: string; body: string }[] = ${JSON.stringify(notes)};\n`,
  );
  console.log(`bundled ${notes.length} notes`);
}
